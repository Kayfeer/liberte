import { invoke } from "@tauri-apps/api/core";
import {
  ExternalE2EEKeyProvider, isE2EESupported, LocalAudioTrack, LocalVideoTrack,
  Room, RoomEvent, Track,
  type Participant, type RemoteParticipant, type RemoteTrack, type RemoteTrackPublication,
} from "livekit-client";
import E2EEWorker from "livekit-client/e2ee-worker?worker";
import {
  captureAudio, captureVideo, disposeAudio, preferences, registerMediaSession, releaseMediaSession,
  type AudioCapture, type CallSession, type Preferences, type SessionOptions,
} from "./mediaSession";

export interface SfuConnection {
  url: string;
  token: string;
  roomName: string;
  /** Generated by the local Rust client from the channel key, never sent to the SFU. */
  encryptionKey: string;
}

function keyBytes(hex: string): Uint8Array<ArrayBuffer> {
  if (!/^[a-f0-9]{64}$/i.test(hex)) throw new Error("Clé de chiffrement SFU invalide.");
  return Uint8Array.from(hex.match(/../g)!, (value) => Number.parseInt(value, 16));
}

function validateConnection(connection: SfuConnection) {
  const url = new URL(connection.url);
  const loopback = ["localhost", "127.0.0.1", "[::1]"].includes(url.hostname);
  if (url.protocol !== "wss:" && !(url.protocol === "ws:" && loopback)) {
    throw new Error("Le serveur SFU doit utiliser WSS (TLS), sauf sur localhost.");
  }
  if (url.username || url.password || !connection.token || !connection.roomName) {
    throw new Error("Configuration SFU invalide.");
  }
}

/**
 * LiveKit transport with mandatory media E2EE. Keys stay in the local client.
 * SDK contract: https://docs.livekit.io/transport/encryption/start/
 */
export class SfuSession implements CallSession {
  private room: Room | null = null;
  private worker: Worker | null = null;
  private audio: AudioCapture | null = null;
  private audioTrack: LocalAudioTrack | null = null;
  private videoTrack: LocalVideoTrack | null = null;
  private settings = preferences();
  private muted = false;
  private started = false;
  private closed = false;
  private encrypted = false;
  private remoteStreams = new Map<string, MediaStream>();
  private mutations: Promise<void> = Promise.resolve();

  constructor(private options: SessionOptions) {}

  private assertOpen() {
    if (this.closed) throw new Error("Appel SFU terminé.");
  }

  private assertEncrypted() {
    this.assertOpen();
    if (!this.encrypted || !this.room?.localParticipant.isE2EEEnabled) {
      throw new Error("Le chiffrement de bout en bout SFU n'est pas actif.");
    }
  }

  private fail(message: string) {
    if (this.closed) return;
    // Stop capture synchronously before any network teardown can await.
    this.options.onError(message);
    void this.stop().catch(() => {}).finally(() => this.options.onClosed?.(message));
  }

  private publishLocalStream() {
    if (this.closed) return;
    this.options.onLocalStream(new MediaStream([
      ...(this.audio?.stream.getAudioTracks() ?? []),
      ...(this.videoTrack ? [this.videoTrack.mediaStreamTrack] : []),
    ]));
  }

  private peer(participant: Participant, state: "connecting" | "connected" = "connected") {
    if (this.closed || participant.identity === this.options.userId) return;
    this.options.onPeer(participant.identity, {
      displayName: participant.name || participant.identity.slice(0, 8),
      state, isMuted: !participant.isMicrophoneEnabled, isVideoEnabled: participant.isCameraEnabled,
    });
  }

  private removeParticipant(participant: RemoteParticipant) {
    this.remoteStreams.delete(participant.identity);
    this.options.onRemoteStream(participant.identity, null);
    this.options.onPeer(participant.identity, null);
  }

  private subscribe(publication: RemoteTrackPublication, participant: RemoteParticipant) {
    if (this.closed) return;
    if (!/^[a-f0-9]{64}$/i.test(participant.identity) || !publication.isEncrypted) {
      this.fail("Un participant SFU propose un média sans chiffrement de bout en bout. Appel arrêté.");
      return;
    }
    publication.setSubscribed(true);
    this.peer(participant);
  }

  private receiveTrack(track: RemoteTrack, publication: RemoteTrackPublication, participant: RemoteParticipant) {
    if (this.closed) return;
    if (!publication.isEncrypted || !this.encrypted) {
      this.fail("Média SFU non chiffré refusé.");
      return;
    }
    const stream = this.remoteStreams.get(participant.identity) ?? new MediaStream();
    stream.addTrack(track.mediaStreamTrack);
    this.remoteStreams.set(participant.identity, stream);
    this.options.onRemoteStream(participant.identity, stream);
    this.peer(participant);
  }

  private bindRoom(room: Room) {
    room.on(RoomEvent.EncryptionError, () => this.fail("Erreur de chiffrement SFU. Vérifiez que tous les participants utilisent la même invitation."));
    room.on(RoomEvent.ParticipantEncryptionStatusChanged, (encrypted, participant) => {
      if (!encrypted && (participant?.isLocal || (participant && this.remoteStreams.has(participant.identity)))) {
        this.fail("Le chiffrement SFU a été désactivé. Appel arrêté.");
      }
    });
    room.on(RoomEvent.ParticipantConnected, (participant) => this.peer(participant));
    room.on(RoomEvent.ParticipantDisconnected, (participant) => this.removeParticipant(participant));
    room.on(RoomEvent.TrackPublished, (publication, participant) => this.subscribe(publication, participant));
    room.on(RoomEvent.TrackSubscribed, (track, publication, participant) => this.receiveTrack(track, publication, participant));
    room.on(RoomEvent.TrackUnsubscribed, (track, _publication, participant) => {
      const stream = this.remoteStreams.get(participant.identity);
      if (!stream || this.closed) return;
      stream.removeTrack(track.mediaStreamTrack);
      this.options.onRemoteStream(participant.identity, stream.getTracks().length ? stream : null);
      this.peer(participant);
    });
    room.on(RoomEvent.TrackMuted, (_publication, participant) => this.peer(participant));
    room.on(RoomEvent.TrackUnmuted, (_publication, participant) => this.peer(participant));
    room.on(RoomEvent.Reconnecting, () => room.remoteParticipants.forEach((participant) => this.peer(participant, "connecting")));
    room.on(RoomEvent.Reconnected, () => {
      try { this.assertEncrypted(); }
      catch { this.fail("Chiffrement SFU indisponible après reconnexion."); return; }
      room.remoteParticipants.forEach((participant) => this.peer(participant));
    });
    room.on(RoomEvent.Moved, () => this.fail("Le serveur a changé la salle SFU. Rejoignez de nouveau le canal."));
    room.on(RoomEvent.Disconnected, () => this.fail("Connexion SFU interrompue. Rejoignez de nouveau l'appel."));
  }

  async start(): Promise<void> {
    if (this.started || this.closed) throw new Error("Session déjà démarrée ou terminée.");
    if (!isE2EESupported() || !navigator.mediaDevices?.getUserMedia) {
      throw new Error("Ce navigateur ne prend pas en charge les appels SFU chiffrés de bout en bout.");
    }
    this.started = true;
    try {
      const connection = await invoke<SfuConnection>("get_sfu_connection", { channelId: this.options.channelId });
      this.assertOpen();
      validateConnection(connection);
      const key = keyBytes(connection.encryptionKey);
      connection.encryptionKey = "";
      const keyProvider = new ExternalE2EEKeyProvider();
      this.worker = new E2EEWorker();
      const room = new Room({
        encryption: { keyProvider, worker: this.worker },
        adaptiveStream: false,
        dynacast: true,
        stopLocalTrackOnUnpublish: true,
      });
      this.room = room;
      this.bindRoom(room);
      try { await keyProvider.setKey(key.buffer); }
      finally { key.fill(0); }
      this.assertOpen();
      await room.setE2EEEnabled(true);
      this.encrypted = true;
      this.assertEncrypted();
      // Explicit ICE config avoids the SDK's default third-party STUN fallback.
      await room.connect(connection.url, connection.token, {
        autoSubscribe: false,
        rtcConfig: { iceServers: this.settings.iceServers },
      });
      connection.token = "";
      this.assertEncrypted();
      if (room.name !== connection.roomName || room.localParticipant.identity !== this.options.userId) {
        throw new Error("Le serveur SFU a renvoyé une salle ou une identité inattendue.");
      }
      const capture = await captureAudio(this.settings);
      if (this.closed) { disposeAudio(capture); this.assertOpen(); }
      this.audio = capture;
      const audio = new LocalAudioTrack(capture.stream.getAudioTracks()[0], undefined, true);
      this.audioTrack = audio;
      this.assertEncrypted();
      const publication = await room.localParticipant.publishTrack(audio, { source: Track.Source.Microphone });
      this.assertEncrypted();
      if (!publication.isEncrypted) throw new Error("Publication audio SFU non chiffrée refusée.");
      capture.raw.getAudioTracks()[0]?.addEventListener("ended", () => {
        if (!this.closed) this.options.onError("Microphone déconnecté. Choisissez un périphérique dans les paramètres.");
      });
      room.remoteParticipants.forEach((participant) => {
        this.peer(participant);
        participant.trackPublications.forEach((publication) => this.subscribe(publication, participant));
      });
      this.assertOpen();
      registerMediaSession(this);
      this.publishLocalStream();
    } catch (error) {
      await this.stop().catch(() => {});
      throw error;
    }
  }

  announce() { /* Presence is provided by the authenticated LiveKit room. */ }

  private mutate(operation: () => Promise<void>): Promise<void> {
    const result = this.mutations.then(async () => { this.assertEncrypted(); await operation(); });
    this.mutations = result.catch(() => {});
    return result;
  }

  setMuted(muted: boolean) {
    if (this.closed) return;
    this.muted = muted;
    this.audio?.raw.getAudioTracks().forEach((track) => { track.enabled = !muted; });
    this.audio?.stream.getAudioTracks().forEach((track) => { track.enabled = !muted; });
    void this.mutate(async () => {
      if (this.muted) await this.audioTrack?.mute();
      else await this.audioTrack?.unmute();
    }).catch(() => this.fail("Impossible de modifier le microphone SFU. Appel arrêté."));
  }

  setVideoEnabled(enabled: boolean): Promise<void> {
    return this.mutate(async () => {
      if (enabled === !!this.videoTrack) return;
      const room = this.room!;
      if (!enabled) {
        const previous = this.videoTrack!;
        // Release the camera before signalling; a transport failure must not
        // reactivate capture after the user has disabled it.
        previous.mediaStreamTrack.enabled = false;
        previous.stop();
        this.videoTrack = null;
        this.publishLocalStream();
        await room.localParticipant.unpublishTrack(previous, true);
      } else {
        const raw = await captureVideo(this.settings);
        if (this.closed) { raw.stop(); this.assertOpen(); }
        const track = new LocalVideoTrack(raw, undefined, true);
        try {
          this.assertEncrypted();
          const publication = await room.localParticipant.publishTrack(track, { source: Track.Source.Camera, simulcast: false });
          this.assertEncrypted();
          if (!publication.isEncrypted) throw new Error("Publication vidéo SFU non chiffrée refusée.");
          this.videoTrack = track;
          this.watchVideo();
        } catch (error) {
          raw.stop();
          await room.localParticipant.unpublishTrack(track, true).catch(() => {});
          throw error;
        }
      }
      this.publishLocalStream();
    });
  }

  private watchVideo() {
    const raw = this.videoTrack?.mediaStreamTrack;
    raw?.addEventListener("ended", () => {
      if (this.closed || this.videoTrack?.mediaStreamTrack !== raw) return;
      void this.setVideoEnabled(false).then(() => this.options.onCameraEnded()).catch((error) => this.options.onError(String(error)));
    }, { once: true });
  }

  applyPreferences(): Promise<void> {
    return this.mutate(async () => {
      const settings = preferences();
      const keys: (keyof Preferences)[] = ["selectedAudioInput", "noiseSuppression", "echoCancellation", "autoGainControl", "voiceIsolation"];
      if (keys.some((key) => settings[key] !== this.settings[key])) {
        const next = await captureAudio(settings);
        if (this.closed) { disposeAudio(next); this.assertOpen(); }
        next.raw.getAudioTracks().forEach((track) => { track.enabled = !this.muted; });
        next.stream.getAudioTracks().forEach((track) => { track.enabled = !this.muted; });
        try { await this.audioTrack!.replaceTrack(next.stream.getAudioTracks()[0], true); }
        catch (error) { disposeAudio(next); throw error; }
        if (this.closed) { disposeAudio(next); this.assertOpen(); }
        disposeAudio(this.audio);
        this.audio = next;
      }
      if (this.audio) this.audio.gain.gain.value = Math.max(0, Math.min(2, settings.inputVolume / 100));
      if (this.videoTrack && settings.selectedVideoInput !== this.settings.selectedVideoInput) {
        const raw = await captureVideo(settings);
        if (this.closed) { raw.stop(); this.assertOpen(); }
        const previous = this.videoTrack.mediaStreamTrack;
        try { await this.videoTrack.replaceTrack(raw, true); }
        catch (error) { raw.stop(); throw error; }
        if (this.closed) { raw.stop(); this.assertOpen(); }
        previous.stop();
        this.watchVideo();
      }
      this.settings = settings;
      this.publishLocalStream();
    });
  }

  retryConnections() {
    if (this.closed) { this.options.onError("Rejoignez de nouveau l'appel SFU."); return; }
    void this.room?.startAudio().catch(() => this.options.onError("Autorisez la lecture audio dans le navigateur."));
  }

  /** Receiver statistics expose actual decoded media for diagnostics. */
  async getStats(): Promise<RTCStatsReport[]> {
    const tracks = [...(this.room?.remoteParticipants.values() ?? [])]
      .flatMap((participant) => [...participant.trackPublications.values()])
      .flatMap((publication) => publication.track ? [publication.track] : []);
    const reports = await Promise.all(tracks.map((track) => track.getRTCStatsReport()));
    return reports.filter((report): report is RTCStatsReport => !!report);
  }

  async stop(): Promise<void> {
    if (this.closed) return;
    this.closed = true;
    this.encrypted = false;
    releaseMediaSession(this);
    disposeAudio(this.audio);
    this.audio = null;
    this.audioTrack?.stop();
    this.audioTrack = null;
    this.videoTrack?.stop();
    this.videoTrack = null;
    this.options.onLocalStream(null);
    for (const userId of this.remoteStreams.keys()) {
      this.options.onRemoteStream(userId, null);
      this.options.onPeer(userId, null);
    }
    this.remoteStreams.clear();
    const room = this.room;
    this.room = null;
    room?.removeAllListeners();
    try { await room?.disconnect(true); }
    finally { this.worker?.terminate(); this.worker = null; }
  }
}

